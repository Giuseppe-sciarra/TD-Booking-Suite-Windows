"""Writes src/TD.App/Ui/Icons.g.cs from the ICONS of suite/core/templatetags/presentation.py: each SVG fragment (path, rect,
circle) as one WPF path data string, so the windows draw the very same icons. python3 tools/gen_icons.py"""
import re,sys
src=open("../suite/core/templatetags/presentation.py").read()
icons=dict(re.findall(r'"(\w+)":\'((?:<[^\']+>)+)\'',src))
NUM=r'[-+]?(?:\d+\.\d+|\.\d+|\d+)(?:e[-+]?\d+)?'
def norm(d):
    out=[]
    for cmd,args in re.findall(r'([MmLlHhVvCcSsQqTtAaZz])([^MmLlHhVvCcSsQqTtAaZz]*)',d):
        nums=re.findall(NUM,args)
        if cmd in "Aa":
            # arc flags may be glued ("0 01 4.9"): split them
            toks=[];s=args;i=0
            vals=[]
            pos=0
            while True:
                group=[]
                for k in range(7):
                    m=re.match(r'[\s,]*',s[pos:]);pos+=m.end()
                    if pos>=len(s):break
                    if k in (3,4):group.append(s[pos]);pos+=1
                    else:
                        m=re.match(NUM,s[pos:]);group.append(m.group(0));pos+=m.end()
                if len(group)<7:break
                vals+=group
            nums=vals
        out.append(cmd+" "+" ".join(nums) if nums else cmd)
    return " ".join(out)
def rect(a):
    x,y,w,h=(float(a[k]) for k in ("x","y","width","height"));r=float(a.get("rx",0))
    if not r:return f"M {x} {y} H {x+w} V {y+h} H {x} Z"
    return (f"M {x+r} {y} H {x+w-r} A {r} {r} 0 0 1 {x+w} {y+r} V {y+h-r} A {r} {r} 0 0 1 {x+w-r} {y+h} H {x+r} A {r} {r} 0 0 1 {x} {y+h-r} V {y+r} A {r} {r} 0 0 1 {x+r} {y} Z")
def circle(a):
    cx,cy,r=float(a["cx"]),float(a["cy"]),float(a["r"])
    return f"M {cx-r} {cy} A {r} {r} 0 1 0 {cx+r} {cy} A {r} {r} 0 1 0 {cx-r} {cy} Z"
lines=["// Generated by tools/gen_icons.py from the web program's icons: do not edit by hand.","namespace TD.App.Ui;","","public static partial class Icons","{","    public static readonly Dictionary<string, string> Data = new()","    {"]
for name,body in icons.items():
    parts=[]
    for tag,attrs in re.findall(r'<(\w+)([^>]*)/>',body):
        a=dict(re.findall(r'([\w-]+)="([^"]*)"',attrs))
        parts.append(norm(a["d"]) if tag=="path" else rect(a) if tag=="rect" else circle(a))
    lines.append(f'        ["{name}"] = "{" ".join(parts)}",')
lines+=["    };","}",""]
open("src/TD.App/Ui/Icons.g.cs","w").write("\n".join(lines));print(len(icons),"icons")
