"""Writes src/TD.Core/Data/Entities.g.cs from the database the Python program created (information_schema): one class per
table, one property per column, named as Dapper maps them (snake_case -> PascalCase). Run again after a schema change:
python tools/gen_entities.py "host=/tmp port=5433 dbname=tdref user=postgres" """
import sys,subprocess,json
dsn=sys.argv[1]
q="""select table_name,column_name,data_type,is_nullable,ordinal_position from information_schema.columns where table_schema='public'
 and table_name not like 'auth_%' and table_name not like 'django_%' order by table_name,ordinal_position"""
out=subprocess.run(["psql",dsn,"-AtF","\t","-c",q],capture_output=True,text=True,check=True).stdout
tables={}
for line in out.splitlines():
    t,c,dt,nul,_=line.split("\t");tables.setdefault(t,[]).append((c,dt,nul=="YES"))
TYPES={"uuid":"Guid","character varying":"string","text":"string","boolean":"bool","integer":"int","smallint":"short","bigint":"long",
 "numeric":"decimal","date":"DateTime","timestamp with time zone":"DateTime","jsonb":"string","bytea":"byte[]","double precision":"double",
 "time without time zone":"TimeSpan","inet":"string"}
REF={"string","byte[]"}
def pascal(s):return "".join(p[:1].upper()+p[1:] for p in s.split("_"))
names={"core_user_groups":None,"core_user_user_permissions":None}
lines=["// Generated by tools/gen_entities.py from the schema of the Python program: do not edit by hand.","#nullable disable","namespace TD.Core.Data;",""]
for t,cols in tables.items():
    if t in names:continue
    cls=pascal(t.split("_",1)[1]) if t.startswith(("core_","tdwin_")) else pascal(t)
    if t.startswith("tdwin_"):cls="Win"+cls
    lines.append(f"[Table(\"{t}\")]")
    lines.append(f"public partial class {cls}")
    lines.append("{")
    for c,dt,nul in cols:
        ty=TYPES[dt];opt="?" if nul and ty not in REF else ""
        lines.append(f"    public {ty}{opt} {pascal(c)} {{ get; set; }}")
    lines.append("}")
    lines.append("")
open("src/TD.Core/Data/Entities.g.cs","w").write("\n".join(lines))
# the columns of each table with the SQL type, for INSERT/UPDATE with the right casts (jsonb, inet)
sch=["// Generated by tools/gen_entities.py: the columns of every table and their SQL types.","namespace TD.Core.Data;","","public static partial class Schema","{",
 "    public static readonly Dictionary<string, (string Column, string Type)[]> Columns = new()","    {"]
for t,cols in tables.items():
    if t in names:continue
    sch.append(f"        [\"{t}\"] = new[] {{ "+", ".join(f'(\"{c}\", \"{dt}\")' for c,dt,_ in cols)+" },")
sch+=["    };","}",""]
open("src/TD.Core/Data/Schema.g.cs","w").write("\n".join(sch))
print(len(tables),"tables")
